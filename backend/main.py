@app.post(
    "/api/chat"
)

def chat(
    payload: dict
):

    question = str(

        payload.get(
            "question",
            ""
        )

    ).strip()


    if len(question) < 2:

        raise HTTPException(

            status_code=422,

            detail=(
                "Question is required."
            ),

        )


    try:

        top_k = int(

            payload.get(
                "top_k",
                DEFAULT_TOP_K
            )

        )

    except Exception:

        top_k = (
            DEFAULT_TOP_K
        )


    top_k = min(

        max(
            top_k,
            2
        ),

        MAX_TOP_K

    )


    session_id = (

        payload.get(
            "session_id"
        )

        or

        str(
            uuid.uuid4()
        )

    )


    history = conversation_memory.get(

        session_id,

        []

    )


    retrieval_query = (
        question
    )


    # --------------------------------------------------------
    # FOLLOW-UP CONTEXT
    # --------------------------------------------------------

    if history:

        recent_questions = [

            item["content"]

            for item in history

            if item["role"]
            ==
            "user"

        ][-2:]


        if recent_questions:

            retrieval_query = (

                " ".join(
                    recent_questions
                )

                +

                " "

                +

                question

            )


    documents = retrieve_context(

        retrieval_query,

        top_k

    )


    # --------------------------------------------------------
    # CONFIDENCE GUARD
    # --------------------------------------------------------

    if (
        not documents
        or
        documents[0]["similarity"]
        <
        MIN_RETRIEVAL_SCORE
    ):

        answer = (
            "I don't have strong enough "
            "verified evidence in Manas's "
            "portfolio to answer that confidently. "
            "I don't want to invent experience."
        )


        conversation_memory.setdefault(
            session_id,
            []
        )


        conversation_memory[
            session_id
        ].extend([

            {
                "role":
                    "user",

                "content":
                    question,
            },

            {
                "role":
                    "assistant",

                "content":
                    answer,
            },

        ])


        return {

            "answer":
                answer,

            "grounded":
                False,

            "session_id":
                session_id,

            "sources":
                [],

        }


    evidence_context = (
        build_context(
            documents
        )
    )


    previous_history = "\n".join(

        [

            (
                f'{item["role"].upper()}: '
                f'{item["content"]}'
            )

            for item in history[-6:]

        ]

    )


    user_prompt = f"""
PREVIOUS CONVERSATION

{previous_history or "None"}


CURRENT QUESTION

{question}


VERIFIED PORTFOLIO EVIDENCE

{evidence_context}


Answer the recruiter using ONLY the verified evidence above.

Conversation history may help interpret follow-up questions,
but it is not independent evidence.
"""


    try:

        completion = (

            groq_client
            .chat
            .completions
            .create(

                model=
                    GROQ_MODEL,

                messages=[

                    {

                        "role":
                            "system",

                        "content":
                            CHAT_SYSTEM_PROMPT,

                    },

                    {

                        "role":
                            "user",

                        "content":
                            user_prompt,

                    },

                ],

                temperature=
                    0.15,

                max_tokens=
                    650,

            )

        )


        answer = (

            completion
            .choices[0]
            .message
            .content
            .strip()

        )


    except Exception as error:

        print(
            "Groq Chat Error:",
            type(error).__name__,
            str(error)
        )


        return {

            "answer":
                (
                    "The portfolio evidence retrieval "
                    "worked, but the language-model "
                    "service is temporarily unavailable."
                ),

            "grounded":
                False,

            "session_id":
                session_id,

            "sources":
                [],

        }


    conversation_memory.setdefault(
        session_id,
        []
    )


    conversation_memory[
        session_id
    ].extend([

        {

            "role":
                "user",

            "content":
                question,

        },

        {

            "role":
                "assistant",

            "content":
                answer,

        },

    ])


    conversation_memory[
        session_id
    ] = conversation_memory[
        session_id
    ][-MAX_MEMORY_MESSAGES:]


    return {

        "answer":
            answer,

        "grounded":
            True,

        "session_id":
            session_id,

        "sources":
            [

                {

                    "id":
                        item["id"],

                    "title":
                        item["title"],

                    "source":
                        item["source"],

                    "category":
                        item["category"],

                    "similarity":
                        round(
                            item["similarity"],
                            4
                        ),

                }

                for item in documents

            ],

    }


