# ============================================================
# LIGHTWEIGHT RETRIEVAL
# ============================================================

def retrieve_context(

    query: str,

    top_k: int = DEFAULT_TOP_K

):

    if not ai_documents:

        return []


    query_terms = tokenize(
        query
    )


    if not query_terms:

        return []


    query_counts = Counter(
        query_terms
    )


    query_weights = {}


    query_norm_squared = 0.0


    for term, frequency in (
        query_counts.items()
    ):

        weight = (

            (
                1.0
                +
                math.log(
                    frequency
                )
            )

            *

            idf_values.get(
                term,
                1.8
            )

        )


        query_weights[
            term
        ] = weight


        query_norm_squared += (
            weight
            *
            weight
        )


    query_norm = (

        math.sqrt(
            query_norm_squared
        )

        or

        1.0

    )


    results = []


    normalized_query = (
        query.lower().strip()
    )


    for index, document in enumerate(
        ai_documents
    ):

        counts = (
            document_term_counts[
                index
            ]
        )


        dot_product = 0.0


        matched_terms = 0


        for term, query_weight in (
            query_weights.items()
        ):

            frequency = counts.get(
                term,
                0
            )


            if frequency <= 0:

                continue


            matched_terms += 1


            document_weight = (

                (
                    1.0
                    +
                    math.log(
                        frequency
                    )
                )

                *

                idf_values.get(
                    term,
                    1.0
                )

            )


            dot_product += (

                query_weight

                *

                document_weight

            )


        score = (

            dot_product

            /

            (
                query_norm
                *
                document_norms[index]
            )

        )


        # ----------------------------------------------------
        # SMALL EXACT-MATCH BOOST
        # ----------------------------------------------------

        searchable = (

            document["title"]

            +

            " "

            +

            document["content"]

        ).lower()


        # Exact query phrase.
        if (
            normalized_query
            and
            normalized_query
            in
            searchable
        ):

            score += 0.20


        # Technology-token coverage.
        if query_terms:

            coverage = (

                matched_terms

                /

                len(
                    set(
                        query_terms
                    )
                )

            )


            score += (
                coverage
                *
                0.08
            )


        result = dict(
            document
        )


        result[
            "similarity"
        ] = float(
            score
        )


        results.append(
            result
        )


    results.sort(

        key=lambda item:
            item["similarity"],

        reverse=True

    )


    return results[
        :top_k
    ]


# ============================================================
# CONTEXT BUILDER
# ============================================================

def build_context(
    documents
):

    blocks = []


    for number, item in enumerate(

        documents,

        start=1

    ):

        blocks.append(

            f"""
EVIDENCE {number}

Title:
{item["title"]}

Source:
{item["source"]}

Category:
{item["category"]}

Content:
{item["content"]}
""".strip()

        )


    return "\n\n---\n\n".join(
        blocks
    )


