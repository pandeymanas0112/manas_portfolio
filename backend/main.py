def normalize_token(
    token: str
):

    return (
        token
        .strip()
        .lower()
    )


def tokenize(
    text: str
):

    if not text:

        return []


    # Keeps useful technology expressions:
    #
    # fastapi
    # c++
    # c#
    # node.js
    # jwt
    # yolov8

    raw_tokens = re.findall(

        r"[a-zA-Z0-9][a-zA-Z0-9+#._/-]*",

        text.lower()

    )


    tokens = []


    for token in raw_tokens:

        token = normalize_token(
            token
        )


        if (
            len(token) <= 1
            and
            token not in {
                "c",
                "r"
            }
        ):

            continue


        if token in STOP_WORDS:

            continue


        tokens.append(
            token
        )


    return tokens


